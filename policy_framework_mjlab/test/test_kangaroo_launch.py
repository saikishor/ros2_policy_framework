"""Policy parameters generated by launch/kangaroo_mjlab.launch.py from lists of model versions."""

import importlib.util
import os

from launch import LaunchContext
from launch.utilities import perform_substitutions
from launch_ros.parameter_descriptions import ParameterFile
import pytest
import yaml

LAUNCH = os.path.join(os.path.dirname(__file__), '..', 'launch', 'kangaroo_mjlab.launch.py')
spec = importlib.util.spec_from_file_location('kangaroo_mjlab_launch', LAUNCH)
launch = importlib.util.module_from_spec(spec)
spec.loader.exec_module(launch)

TEMPLATE = {
    'loco': {'model_path': '', 'terms': {'command': {'topic': '/cmd_vel'}}},
    'imitation': {'model_path': '', 'interruptible': False},
}


@pytest.fixture
def models(tmp_path):
    for task, version in [('loco', 'v1'), ('loco', 'v2'), ('imitation', 'v30'),
                          ('imitation', 'v40')]:
        os.makedirs(tmp_path / 'full_body_4dof' / task / f'{task}_{version}_mjlab')
    return str(tmp_path)


def test_one_policy_per_version_with_the_first_loco_active(models):
    params = launch.policy_parameters(
        TEMPLATE, models, 'full_body_4dof', ['v2', 'v1'], ['v30', 'v40'], [300, 120])
    assert params['policies'] == ['loco_v2', 'loco_v1', 'imitation_v30', 'imitation_v40']
    assert params['loco_v1']['model_path'] == os.path.join(
        models, 'full_body_4dof', 'loco', 'loco_v1_mjlab')
    assert params['loco_v1']['terms'] == {'command': {'topic': '/cmd_vel'}}
    assert 'max_steps' not in params['loco_v1']
    assert params['imitation_v40']['max_steps'] == 120
    assert params['imitation_v40']['interruptible'] is False


def test_policies_do_not_share_the_template(models):
    params = launch.policy_parameters(TEMPLATE, models, 'full_body_4dof', ['v1', 'v2'], [], [])
    params['loco_v1']['terms']['command']['topic'] = '/other'
    assert params['loco_v2']['terms']['command']['topic'] == '/cmd_vel'
    assert TEMPLATE['loco']['terms']['command']['topic'] == '/cmd_vel'


def test_overrides_apply_to_every_policy(models):
    params = launch.policy_parameters(
        TEMPLATE, models, 'full_body_4dof', ['v1'], ['v30'], [300],
        overrides={'gains_as_commands': True})
    assert params['loco_v1']['gains_as_commands'] is True
    assert params['imitation_v30']['gains_as_commands'] is True


def test_known_motions_have_default_frames(models):
    params = launch.policy_parameters(TEMPLATE, models, 'full_body_4dof', ['v1'], ['v30'], [])
    assert params['imitation_v30']['max_steps'] == 300


def test_unknown_motions_need_their_frames(models):
    with pytest.raises(ValueError, match='imitation_frames'):
        launch.policy_parameters(TEMPLATE, models, 'full_body_4dof', ['v1'], ['v40'], [])
    with pytest.raises(ValueError, match='imitation_frames'):
        launch.policy_parameters(TEMPLATE, models, 'full_body_4dof', ['v1'], ['v30', 'v40'], [1])


def test_needs_a_loco_policy_and_existing_models(models):
    with pytest.raises(ValueError, match='loco_models'):
        launch.policy_parameters(TEMPLATE, models, 'full_body_4dof', [], ['v30'], [300])
    with pytest.raises(FileNotFoundError):
        launch.policy_parameters(TEMPLATE, models, 'full_body_4dof', ['v9'], [], [])


CONFIG = os.path.join(os.path.dirname(__file__), '..', 'config', 'kangaroo')


def host_parameters(name):
    with open(os.path.join(CONFIG, name)) as f:
        # The controller template has @KEY@ placeholders that are not valid YAML values.
        return yaml.safe_load(f.read().replace('@ASYNC_INFERENCE@', 'false'))


@pytest.mark.parametrize('host, node', [('policy_node.yaml', 'policy_node'),
                                        ('policy_controller.yaml', 'policy_controller')])
def test_velocity_command_comes_from_one_shared_source(host, node):
    # One /cmd_vel subscription for every policy, not one TwistCommandTerm per policy.
    params = host_parameters(host)[node]['ros__parameters']
    assert 'cmd_vel' in params['sources']
    assert params['cmd_vel'] == {'type': 'policy_framework/TwistSource', 'topic': '/cmd_vel',
                                 'timeout': 1.0}
    with open(os.path.join(CONFIG, 'policies.yaml')) as f:
        template = yaml.safe_load(f)
    assert all('terms' not in policy for policy in template.values())


def test_safety_checks_only_on_the_real_robot():
    # The simulation exposes neither <joint>/absolute_position nor <actuator>/mode.
    assert launch.safety_parameters(CONFIG, sim=True) == []
    assert launch.safety_parameters(CONFIG, sim=False) == [os.path.join(CONFIG, 'safety.yaml')]


def launch_actions(mode, use_sim_time, models_dir, **arguments):
    """Actions of the launch with its defaults, for the given mode and use_sim_time."""
    context = LaunchContext()
    for action in launch.generate_launch_description().entities:
        if getattr(action, 'default_value', None) is not None:
            context.launch_configurations[action.name] = perform_substitutions(
                context, action.default_value)
    context.launch_configurations.update(
        mode=mode, use_sim_time=use_sim_time, robot_type='full_body_4dof',
        models_dir=models_dir, loco_models='v1', imitation_models='v30')
    context.launch_configurations.update(arguments)
    return launch.launch_setup(context)


@pytest.mark.parametrize('mode', ['controller', 'controller_async'])
def test_controller_loads_the_safety_checks_on_the_real_robot(models, mode):
    def loads_safety(use_sim_time):
        [spawner] = launch_actions(mode, use_sim_time, models)
        return any(a.endswith('safety.yaml') for a in spawner._Node__arguments)

    assert loads_safety('false')
    assert not loads_safety('true')


def test_policy_node_has_no_safety_checks(models):
    # No source of the node feeds <joint>/absolute_position or <actuator>/mode yet.
    _, node = launch_actions('node', 'false', models)
    files = [perform_substitutions(LaunchContext(), p.param_file)
             for p in node._Node__parameters if isinstance(p, ParameterFile)]
    assert any(f.endswith('policy_node.yaml') for f in files)
    assert not any(f.endswith('safety.yaml') for f in files)


def test_use_sim_time_is_the_only_simulation_switch():
    # One flag for simulation: a separate one could be forgotten while use_sim_time is set.
    names = [a.name for a in launch.generate_launch_description().entities
             if hasattr(a, 'default_value')]
    assert 'use_sim_time' in names
    assert 'sim' not in names


CONFIG_POLICIES = {
    'policies': ['walk', 'dance'],
    'walk': {'model': 'loco/v2', 'interruptible': True},
    'dance': {'model': 'imitation/v40', 'max_steps': 120},
}


def test_config_resolves_each_model_on_its_task_template(models):
    params = launch.resolve_policies(TEMPLATE, models, 'full_body_4dof', CONFIG_POLICIES)
    assert params['policies'] == ['walk', 'dance']
    assert params['walk']['model_path'] == os.path.join(
        models, 'full_body_4dof', 'loco', 'loco_v2_mjlab')
    assert 'model' not in params['walk']
    assert params['walk']['terms'] == {'command': {'topic': '/cmd_vel'}}
    assert params['walk']['interruptible'] is True
    assert params['dance']['interruptible'] is False
    assert params['dance']['max_steps'] == 120
    assert CONFIG_POLICIES['walk']['model'] == 'loco/v2'


def test_config_imitation_without_frames_uses_the_known_motion(models):
    params = launch.resolve_policies(TEMPLATE, models, 'full_body_4dof', {
        'policies': ['walk', 'dance'], 'walk': {'model': 'loco/v1'},
        'dance': {'model': 'imitation/v30'}})
    assert params['dance']['max_steps'] == 300
    with pytest.raises(ValueError, match='max_steps'):
        launch.resolve_policies(TEMPLATE, models, 'full_body_4dof', {
            'policies': ['walk', 'dance'], 'walk': {'model': 'loco/v1'},
            'dance': {'model': 'imitation/v40'}})


@pytest.mark.parametrize('config, error', [
    ({'policies': ['dance'], 'dance': {'model': 'imitation/v30'}}, 'first policy'),
    ({'policies': ['walk'], 'walk': {'model': 'v1'}}, 'task/version'),
    ({'policies': ['walk'], 'walk': {'model': 'run/v1'}}, 'unknown task'),
    ({'policies': ['walk'], 'walk': {}}, 'model'),
    ({'policies': []}, 'first policy'),
])
def test_config_rejects_malformed_policies(models, config, error):
    with pytest.raises(ValueError, match=error):
        launch.resolve_policies(TEMPLATE, models, 'full_body_4dof', config)


@pytest.mark.parametrize('content, error', [
    ('', 'empty'),
    (yaml.safe_dump({'policy_controller': {'ros__parameters': CONFIG_POLICIES}}),
     'ros__parameters'),
])
def test_read_config_rejects_a_file_that_is_not_a_policy_config(tmp_path, content, error):
    config = tmp_path / 'policies.yaml'
    config.write_text(content)
    with pytest.raises(ValueError, match=error):
        launch.read_config(str(config))


def test_shipped_example_config_resolves(models):
    # Relative to config/kangaroo/; its models are created in the models fixture layout.
    config = launch.read_config('examples/full_body_4dof_loco_imitation.yaml')
    for policy in config['policies']:
        task, version = config[policy]['model'].split('/')
        os.makedirs(os.path.join(models, 'full_body_4dof', task, f'{task}_{version}_mjlab'),
                    exist_ok=True)
    with open(os.path.join(CONFIG, 'policies.yaml')) as f:
        template = yaml.safe_load(f)
    params = launch.resolve_policies(template, models, 'full_body_4dof', config)
    assert params['policies'][0].startswith('loco')


def spawner_policies(spawner):
    """Policy parameters of the policies param file given to the controller spawner."""
    arguments = spawner._Node__arguments
    with open(arguments[arguments.index('--param-file') + 1]) as f:
        return yaml.safe_load(f)['/**']['ros__parameters']


def test_controller_config_policies_get_the_controller_overrides(models, tmp_path):
    config = tmp_path / 'policies.yaml'
    config.write_text(yaml.safe_dump(CONFIG_POLICIES))
    [spawner] = launch_actions('controller', 'true', models, config=str(config),
                               loco_models='', imitation_models='')
    params = spawner_policies(spawner)
    assert params['policies'] == ['walk', 'dance']
    assert params['walk']['gains_as_commands'] is True
    assert params['dance']['gains_controller'] == ''


def test_config_excludes_the_version_arguments(models, tmp_path):
    config = tmp_path / 'policies.yaml'
    config.write_text(yaml.safe_dump(CONFIG_POLICIES))
    with pytest.raises(ValueError, match='loco_models'):
        launch_actions('controller', 'true', models, config=str(config))
